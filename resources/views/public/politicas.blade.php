<div class="content">

    <span class="badge-ley">Ley Estatutaria 1581 de 2012 — Colombia</span>

    <div class="alert-base">
        Al registrar su ingreso como visitante, usted autoriza el tratamiento de sus datos personales conforme a esta política y a la normativa colombiana vigente en materia de protección de datos.
    </div>

    <div class="section-box">
        <h2>1. Responsable del Tratamiento</h2>
        <p>La empresa propietaria de las instalaciones que usted visita es responsable del tratamiento de sus datos personales recolectados a través de este sistema de control de acceso y registro de visitantes.</p>
        <p>Para ejercer sus derechos o presentar consultas y reclamos, puede dirigirse a los canales de contacto habilitados por la empresa en sus instalaciones.</p>
    </div>

    <div class="section-box">
        <h2>2. Datos Personales Recolectados</h2>
        <p>En el marco del registro de visitantes se recolectan los siguientes datos:</p>
        <ul>
            <li>Número de cédula de ciudadanía o documento de identidad</li>
            <li>Nombre completo</li>
            <li>Número de teléfono de contacto</li>
            <li>Nombre de la empresa o entidad a la que pertenece</li>
            <li>Entidad Promotora de Salud (EPS) y Administradora de Riesgos Laborales (ARL)</li>
            <li>Placa del vehículo (cuando aplique)</li>
            <li>Fotografía facial tomada al momento del ingreso y/o salida</li>
            <li>Fecha, hora de entrada y salida</li>
            <li>Ubicación geográfica al momento del registro (coordenadas GPS)</li>
            <li>Persona o área visitada dentro de las instalaciones</li>
        </ul>
    </div>

    <div class="section-box">
        <h2>3. Finalidades del Tratamiento</h2>
        <p>Sus datos personales serán tratados exclusivamente para las siguientes finalidades:</p>
        <ul>
            <li><strong>Control de acceso y seguridad:</strong> gestionar el ingreso y salida de visitantes a las instalaciones.</li>
            <li><strong>Cumplimiento normativo:</strong> atender obligaciones legales en materia de seguridad y salud en el trabajo (Decreto 1072 de 2015, Resolución 0312 de 2019).</li>
            <li><strong>Verificación de inducción:</strong> comprobar que el visitante ha recibido la inducción de seguridad requerida según los procedimientos internos.</li>
            <li><strong>Auditoría e investigación de incidentes:</strong> atender requerimientos de autoridades competentes o investigar eventos ocurridos en las instalaciones.</li>
            <li><strong>Estadísticas internas:</strong> elaborar reportes anónimos sobre flujo de visitantes para mejora de procesos.</li>
        </ul>
    </div>

    <div class="section-box">
        <h2>4. Base Legal del Tratamiento</h2>
        <p>El tratamiento de sus datos personales se fundamenta en:</p>
        <ul>
            <li><strong>Consentimiento del titular</strong> (Art. 9, Ley 1581 de 2012): el cual usted otorga de manera libre, expresa e informada al marcar la casilla de aceptación en el formulario de registro.</li>
            <li><strong>Obligación legal:</strong> normativas de seguridad y salud en el trabajo que exigen el control de ingreso de personas a las instalaciones.</li>
            <li><strong>Interés legítimo</strong> del responsable en garantizar la seguridad de sus instalaciones, trabajadores y bienes.</li>
        </ul>
    </div>

    <div class="section-box">
        <h2>5. Derechos del Titular</h2>
        <p>Conforme al artículo 8 de la Ley 1581 de 2012, usted tiene derecho a:</p>
        <ul>
            <li><strong>Conocer</strong> los datos personales que hemos recolectado sobre usted.</li>
            <li><strong>Actualizar</strong> sus datos cuando sean inexactos, incompletos o desactualizados.</li>
            <li><strong>Rectificar</strong> información que no corresponda a la realidad.</li>
            <li><strong>Suprimir</strong> sus datos cuando no sean necesarios para la finalidad que motivó su recolección, salvo que exista obligación legal de conservarlos.</li>
            <li><strong>Revocar</strong> el consentimiento otorgado para el tratamiento, en la medida en que no exista una obligación legal que lo impida.</li>
            <li><strong>Presentar quejas</strong> ante la Superintendencia de Industria y Comercio (SIC) por infracciones a la normativa de protección de datos.</li>
        </ul>
    </div>

    <div class="section-box">
        <h2>6. Conservación de los Datos</h2>
        <p>Los datos recolectados serán conservados durante el tiempo que sea necesario para cumplir las finalidades descritas y de acuerdo con los plazos establecidos por la normativa aplicable en materia de seguridad y salud en el trabajo.</p>
        <p>Las fotografías y registros de acceso se conservarán por un período mínimo de <strong>dos (2) años</strong>, salvo que una norma legal exija un período mayor o que el titular solicite su supresión en los casos que procedan.</p>
    </div>

    <div class="section-box">
        <h2>7. Transferencia y Transmisión de Datos</h2>
        <p>Sus datos personales <strong>no serán vendidos, cedidos ni compartidos</strong> con terceros con fines comerciales. Podrán ser compartidos únicamente con:</p>
        <ul>
            <li>Autoridades judiciales o administrativas que lo requieran por mandato legal.</li>
            <li>Proveedores tecnológicos que actúen como encargados del tratamiento bajo contrato y con las mismas garantías de seguridad.</li>
        </ul>
    </div>

    <div class="section-box">
        <h2>8. Seguridad de la Información</h2>
        <p>Implementamos medidas técnicas, humanas y administrativas para proteger sus datos personales contra acceso no autorizado, pérdida, alteración o divulgación indebida, en cumplimiento del principio de seguridad establecido en el artículo 4 literal g) de la Ley 1581 de 2012.</p>
    </div>

    <div class="section-box">
        <h2>9. Tratamiento de Datos Sensibles</h2>
        <p>La fotografía facial constituye un dato personal sensible según el artículo 5 de la Ley 1581 de 2012. Su recolección está justificada por razones de seguridad de las instalaciones y control de acceso. Usted tiene el derecho de no autorizar su tratamiento; no obstante, en ese caso no podrá completar el registro de ingreso.</p>
    </div>

    <div class="section-box">
        <h2>10. Vigencia y Modificaciones</h2>
        <p>Esta política entra en vigencia a partir de su publicación. El responsable del tratamiento se reserva el derecho de actualizarla para adaptarse a cambios normativos o modificaciones en sus procesos internos, lo cual será comunicado oportunamente.</p>
        <p class="fecha-actualizacion">Última actualización: julio de 2026</p>
    </div>

